import type { AnyContent, ConfigurationWithContent, WriterHook } from '@content-collections/core';
import { defineConfig } from '@content-collections/core';

export type { GetTypeByName } from '@content-collections/core';
export { defineCollection } from '@content-collections/core';
export { compileMDX } from './lib/compile-mdx.js';

const generatedStamp = /^\/\/ generated by content-collections at .*\n\n/;
const upstreamTypesImport = 'import { GetTypeByName } from "@content-collections/core";';

/**
 * `index.js` loses its build timestamp, so an unchanged build writes the same bytes. `index.d.ts` imports
 * `GetTypeByName` from this package, so apps do not need `@content-collections/core` installed.
 */
const generatedFileHooks: WriterHook[] = [
  ({ fileType, content }) => {
    if (fileType === 'javascript') return { content: content.replace(generatedStamp, '') };
    if (fileType === 'typeDefinition') {
      return {
        content: content.replace(upstreamTypesImport, 'import type { GetTypeByName } from "@arki/content/config";'),
      };
    }
    return { content };
  },
];

/** The app's content config: its collections, plus the hooks that keep generated files stable and self-contained. */
export function defineContentConfig<TCollections extends AnyContent[]>(config: {
  content: TCollections;
}): ConfigurationWithContent<TCollections> {
  return defineConfig({ content: config.content, hooks: { writer: generatedFileHooks } });
}
