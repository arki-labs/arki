// Regenerates src/data/iso4217.ts from the official ISO 4217 list published by
// SIX, the maintenance agency. Development tool only: the library itself has no
// network code.
//
//   node scripts/generate-iso4217.mjs            # download the current list
//   node scripts/generate-iso4217.mjs list.xml   # use a local copy
//
// Each currency becomes 7 characters: code (3), numeric code (3), minor-unit
// digits (1). Codes with no minor unit in ISO (gold, test code, ...) get '-'.

import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';

const localPath = process.argv[2];
const xml = localPath === undefined ? await (await fetch(SOURCE)).text() : readFileSync(localPath, 'utf8');

const published = /Pblshd="([^"]+)"/.exec(xml)?.[1];
if (published === undefined) throw new Error('Could not find the publication date in the ISO 4217 list');

const field = (entry, tag) => new RegExp(`<${tag}[^>]*>([^<]*)</${tag}>`).exec(entry)?.[1];
const currencies = new Map();
for (const [, entry] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const code = field(entry, 'Ccy');
  if (code === undefined) continue; // territories with no universal currency
  const numeric = field(entry, 'CcyNbr');
  const minor = field(entry, 'CcyMnrUnts');
  if (!/^[A-Z]{3}$/.test(code) || !/^\d{3}$/.test(numeric ?? '') || !/^(\d|N\.A\.)$/.test(minor ?? '')) {
    throw new Error(`Unexpected ISO 4217 entry: ${code} ${numeric} ${minor}`);
  }
  const packed = `${code}${numeric}${minor === 'N.A.' ? '-' : minor}`;
  const previous = currencies.get(code);
  if (previous !== undefined && previous !== packed) {
    throw new Error(`ISO 4217 lists ${code} twice with different data`);
  }
  currencies.set(code, packed);
}

const table = [...currencies.keys()]
  .sort()
  .map(code => currencies.get(code))
  .join('');

const output = `// Generated by scripts/generate-iso4217.mjs. Do not edit by hand.
// Source: ISO 4217 list one, published by SIX on ${published}. ${currencies.size} currencies.

/** Publication date of the ISO 4217 list this table was built from. */
export const ISO_4217_VERSION = '${published}';

/**
 * Every active ISO 4217 currency, 7 characters each: alphabetic code (3),
 * numeric code (3), minor-unit digits (1). '-' marks a code with no minor
 * unit in ISO (gold, the test code, ...); those are treated as 0 digits.
 */
export const ISO_4217 =
  '${table}';
`;

writeFileSync(new URL('../src/data/iso4217.ts', import.meta.url), output);
console.log(`ISO 4217 ${published}: ${currencies.size} currencies, ${table.length} bytes`);
