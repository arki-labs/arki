/**
 * The README section between `<!-- bench:start -->` and `<!-- bench:end -->`:
 * replace it with a rendered result, or check that it still matches the suite.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

import type { BenchResult } from '../core/types.js';

export const START_MARKER = '<!-- bench:start -->';
export const END_MARKER = '<!-- bench:end -->';

const META_PATTERN = /<!-- bench:meta (\{.*?\}) -->/;

export type ReadmeMeta = {
  schema?: number;
  suite?: string;
  specHash?: string;
  profile?: string;
  date?: string;
  harness?: string;
};

export class ReadmeError extends Error {
  override name = 'ReadmeError';
}

function count(text: string, marker: string): number {
  return text.split(marker).length - 1;
}

/** Finds the one marked section, or explains exactly what is wrong with the markers. */
function locate(path: string, text: string): { problem: string } | { start: number; end: number } {
  const starts = count(text, START_MARKER);
  const ends = count(text, END_MARKER);
  const hint = `Put ${START_MARKER} and ${END_MARKER} on their own lines where the benchmark section goes.`;
  if (starts === 0 && ends === 0) return { problem: `${path} has no benchmark markers. ${hint}` };
  if (starts === 0) return { problem: `${path} has ${END_MARKER} but no ${START_MARKER}. ${hint}` };
  if (ends === 0) return { problem: `${path} has ${START_MARKER} but no ${END_MARKER}. ${hint}` };
  if (starts > 1) return { problem: `${path} has ${starts} ${START_MARKER} markers; keep exactly one pair.` };
  if (ends > 1) return { problem: `${path} has ${ends} ${END_MARKER} markers; keep exactly one pair.` };
  const start = text.indexOf(START_MARKER);
  const end = text.indexOf(END_MARKER);
  if (end < start) return { problem: `${path} has ${END_MARKER} before ${START_MARKER}; swap them.` };
  return { start: start + START_MARKER.length, end };
}

/** Replaces the marked section of a README. Throws `ReadmeError` when the markers are missing, duplicated or out of order. */
export function writeReadme(path: string, markdown: string): void {
  if (!existsSync(path))
    throw new ReadmeError(`${path} does not exist. Create it with ${START_MARKER} and ${END_MARKER} markers first.`);
  const text = readFileSync(path, 'utf8');
  const found = locate(path, text);
  if ('problem' in found) throw new ReadmeError(found.problem);
  if (markdown.includes(START_MARKER) || markdown.includes(END_MARKER)) {
    throw new ReadmeError(
      'The rendered section contains a bench marker; refusing to write a README that could not be updated again.',
    );
  }
  const next = `${text.slice(0, found.start)}\n${markdown.trim()}\n${text.slice(found.end)}`;
  if (next !== text) writeFileSync(path, next);
}

/** Reads the `bench:meta` line of the marked section, if there is one. */
export function readReadmeMeta(path: string): { meta?: ReadmeMeta; problem?: string } {
  if (!existsSync(path)) return { problem: `${path} does not exist` };
  const text = readFileSync(path, 'utf8');
  const found = locate(path, text);
  if ('problem' in found) return { problem: found.problem };
  const section = text.slice(found.start, found.end);
  if (section.trim() === '') return { problem: `the benchmark section of ${path} is empty` };
  const match = META_PATTERN.exec(section);
  if (!match?.[1])
    return { problem: `the benchmark section of ${path} has no bench:meta line (it was not generated by arki-bench)` };
  try {
    const parsed: unknown = JSON.parse(match[1]);
    if (typeof parsed !== 'object' || parsed === null)
      return { problem: `the bench:meta line of ${path} is not an object` };
    const fields = new Map<string, unknown>(Object.entries(parsed));
    const string = (key: string): string | undefined => {
      const value = fields.get(key);
      return typeof value === 'string' ? value : undefined;
    };
    const schema = fields.get('schema');
    return {
      meta: {
        schema: typeof schema === 'number' ? schema : undefined,
        suite: string('suite'),
        specHash: string('specHash'),
        profile: string('profile'),
        date: string('date'),
        harness: string('harness'),
      },
    };
  } catch {
    return { problem: `the bench:meta line of ${path} is not valid JSON` };
  }
}

/** The fields `checkReadme` needs; a full `BenchResult` fits. */
export type ReadmeTarget = Pick<BenchResult, 'schema'> & { suite: Pick<BenchResult['suite'], 'id' | 'specHash'> };

/**
 * Is the README section generated from this suite as it is now? Compares the
 * section's meta line with the result's schema, suite id and spec hash.
 */
export function checkReadme(path: string, result: ReadmeTarget): { upToDate: boolean; reason?: string } {
  const { meta, problem } = readReadmeMeta(path);
  if (!meta) return { upToDate: false, reason: problem ?? 'no benchmark section' };
  if (meta.schema !== result.schema) {
    return {
      upToDate: false,
      reason: `the section uses result schema ${meta.schema ?? 'unknown'}; this arki-bench writes schema ${result.schema}`,
    };
  }
  if (meta.suite !== undefined && meta.suite !== result.suite.id) {
    return { upToDate: false, reason: `the section is for suite "${meta.suite}", not "${result.suite.id}"` };
  }
  if (meta.specHash !== result.suite.specHash) {
    return {
      upToDate: false,
      reason: `the suite changed since the section was generated (spec ${meta.specHash ?? 'unknown'} → ${result.suite.specHash})`,
    };
  }
  return { upToDate: true };
}
