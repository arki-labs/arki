/**
 * The self-contained copy of the site data contract that `site` writes to
 * `<out>/src/generated/site-schema.ts`.
 *
 * The site lives in another repo, so it cannot import
 * `@arki/arki-release/site-schema`. It gets a generated copy instead, made
 * from the source modules below in dependency order: each module's import
 * declarations are dropped and the rest of its text is copied as is. The only
 * import a source may have, other than an earlier source in the list, is
 * `import { z } from 'zod';`, so the copy depends on zod alone. Nothing is
 * restated by hand: every schema is still written once, in its source module.
 */

import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(here, '..', '..', '..');

/** Where `site` writes the copy, relative to `--out`. */
export const SITE_SCHEMA_COPY_FILE = path.join('src', 'generated', 'site-schema.ts');

/** The source modules of the copy, in dependency order: a module may import only `zod` and modules above it. */
export const SITE_SCHEMA_SOURCES: readonly string[] = [
  createRequire(import.meta.url).resolve('@arki/library-tooling/error-index-schema'),
  path.join(here, 'doc-examples-report-schema.ts'),
  path.join(here, 'site-schema.ts'),
];

/** The one import a source module may keep. The copy starts with it. */
const ZOD_IMPORT = "import { z } from 'zod';";

const HEADER = [
  '// GENERATED by `bun release:arki site`. Do not edit: rerun the command instead.',
  '// Source: tooling/arki-release/src/site-schema.ts in arki-labs/arki, with the schema',
  '// modules it imports copied in dependency order. It depends on zod only.',
].join('\n');

/** Resolves an import of `fromFile` to a file path: relative specifiers get `.ts`, bare ones go through Node resolution. */
function resolveImport(fromFile: string, specifier: string): string {
  if (specifier.startsWith('.')) return path.resolve(path.dirname(fromFile), `${specifier}.ts`);
  return createRequire(fromFile).resolve(specifier);
}

/** Renders the copy from `sources`; throws when a source imports anything but zod and earlier sources. */
export function renderSiteSchemaCopy(sources: readonly string[] = SITE_SCHEMA_SOURCES): string {
  const copied = new Set<string>();
  const sections: string[] = [];
  for (const file of sources) {
    const label = path.relative(REPO_ROOT, file);
    const text = readFileSync(file, 'utf8');
    const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
    let docEnd = -1;
    let bodyStart = 0;
    let pastImports = false;
    for (const statement of source.statements) {
      if (ts.isExportDeclaration(statement) && statement.moduleSpecifier !== undefined)
        throw new Error(`${label}: re-exports from another module cannot be copied; export the schema from its own module.`);
      if (!ts.isImportDeclaration(statement)) {
        pastImports = true;
        continue;
      }
      if (pastImports) throw new Error(`${label}: imports must come before any other statement.`);
      if (!ts.isStringLiteral(statement.moduleSpecifier))
        throw new Error(`${label}: an import specifier is not a string literal.`);
      const specifier = statement.moduleSpecifier.text;
      if (specifier === 'zod') {
        if (statement.getText(source) !== ZOD_IMPORT)
          throw new Error(`${label}: import zod as \`${ZOD_IMPORT}\`, the one zod import the copy keeps.`);
      } else if (!copied.has(resolveImport(file, specifier))) {
        throw new Error(
          `${label}: imports '${specifier}', which is not an earlier module in SITE_SCHEMA_SOURCES. The copy may depend on zod only.`,
        );
      }
      if (docEnd === -1) docEnd = statement.getStart(source);
      bodyStart = statement.end;
    }
    copied.add(file);
    const doc = docEnd === -1 ? '' : text.slice(0, docEnd).trim();
    const body = text.slice(bodyStart).trim();
    sections.push([`// ---- ${label} ----`, ...(doc === '' ? [] : [doc]), body].join('\n\n'));
  }
  return `${HEADER}\n\n${ZOD_IMPORT}\n\n${sections.join('\n\n')}\n`;
}
